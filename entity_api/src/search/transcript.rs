//! Transcript searcher: FTS over `transcript_segments`, anchored to a
//! relationship through the transcription's coaching session.
//!
//! Two things set it apart from the other searchers. It matches the stored
//! `tsv` column rather than a `to_tsvector(...)` expression: the table is the
//! largest searched, and re-parsing every candidate row's text cost seconds at
//! realistic sizes. And hits are grouped: a transcription contributes at most
//! [`SEGMENTS_PER_TRANSCRIPTION`] segments, all carrying the group's best rank,
//! so one long session cannot fill a page.

use async_trait::async_trait;
use sea_orm::entity::prelude::{DateTime, DateTimeWithTimeZone};
use sea_orm::sea_query::{Asterisk, Expr, Func, Order, Query, SelectStatement, WindowStatement};
use sea_orm::{
    ColumnTrait, DatabaseConnection, EntityTrait, ExprTrait, FromQueryResult, JoinType,
    QueryFilter, QuerySelect, QueryTrait, RelationTrait, Select,
};

use super::{
    compile_query, cursor_condition, Core, FtsExpressions, Hit, HitType, Request, TimeRange,
    TranscriptHit,
};
use crate::error::Error;
use entity::transcript_segment::{Column, Entity, Relation};
use entity::{coaching_relationships, coaching_sessions, transcription, Id};

/// Raw-text source for snippets.
pub(super) const TEXT_EXPR: &str = r#""transcript_segments"."text""#;

/// The stored tsvector of `text`, generated by the column added in
/// `migration/src/m20261124_000000_add_transcript_segment_search_column.rs`
/// and indexed by `idx_transcript_segments_tsv`.
const TSV_EXPR: &str = r#""transcript_segments"."tsv""#;

/// Also stated in `TranscriptHit`'s API doc; change both together.
const SEGMENTS_PER_TRANSCRIPTION: i32 = 3;

/// Output columns of the ranking subquery that the grouped query filters and sorts on.
const SCORE: &str = "score";
const RANK_IN_TRANSCRIPTION: &str = "rn";

/// Shown only if the domain cannot resolve the session's title.
const TITLE_FALLBACK: &str = "Transcript";

#[derive(Debug, FromQueryResult)]
struct Row {
    id: Id,
    score: f32,
    transcription_id: Id,
    speaker_label: String,
    start_ms: i32,
    end_ms: i32,
    created_at: DateTimeWithTimeZone,
    coaching_session_id: Id,
    coaching_relationship_id: Id,
    session_date: DateTime,
    organization_id: Id,
}

pub struct Searcher;

#[async_trait]
impl super::Searcher for Searcher {
    fn hit_type(&self) -> HitType {
        HitType::Transcript
    }

    async fn search(&self, db: &DatabaseConnection, req: &Request<'_>) -> Result<Vec<Hit>, Error> {
        let rows = Row::find_by_statement(db.get_database_backend().build(&statement(req)))
            .all(db)
            .await?;

        Ok(rows
            .into_iter()
            .map(|r| {
                Hit::Transcript(TranscriptHit {
                    core: Core {
                        id: r.id,
                        score: r.score,
                        title: TITLE_FALLBACK.to_string(),
                        snippet: None,
                        created_at: r.created_at,
                        // Segments are written once and never edited.
                        updated_at: None,
                        organization_id: r.organization_id,
                    },
                    transcription_id: r.transcription_id,
                    coaching_session_id: r.coaching_session_id,
                    coaching_relationship_id: r.coaching_relationship_id,
                    session_date: r.session_date,
                    start_ms: r.start_ms,
                    end_ms: r.end_ms,
                    speaker_label: r.speaker_label,
                })
            })
            .collect())
    }
}

/// The top segments per transcription, then the cursor keyset, ordering and
/// fetch limit over those groups. Window functions are evaluated after
/// `WHERE`, so the grouping has to be a subquery: the cursor must filter
/// ranked rows, not the rows being ranked.
fn statement(req: &Request<'_>) -> SelectStatement {
    let cq = compile_query(req.q);
    let fts = FtsExpressions::stored(TSV_EXPR);
    let f = req.filters;

    let per_transcription = || WindowStatement::partition_by((Entity, Column::TranscriptionId));
    let mut best_first = per_transcription();
    best_first
        .order_by_expr(fts.score(&cq), Order::Desc)
        .order_by((Entity, Column::Id), Order::Asc);

    let matches = Entity::find()
        .select_only()
        .column(Column::Id)
        .column(Column::TranscriptionId)
        .column(Column::SpeakerLabel)
        .column(Column::StartMs)
        .column(Column::EndMs)
        .column(Column::CreatedAt)
        .column(transcription::Column::CoachingSessionId)
        .column(coaching_sessions::Column::CoachingRelationshipId)
        .column_as(coaching_sessions::Column::Date, "session_date")
        .column(coaching_relationships::Column::OrganizationId)
        .join(JoinType::InnerJoin, Relation::Transcriptions.def())
        .join(
            JoinType::InnerJoin,
            transcription::Relation::CoachingSessions.def(),
        )
        .join(
            JoinType::InnerJoin,
            coaching_sessions::Relation::CoachingRelationships.def(),
        )
        .filter(fts.match_condition(&cq))
        // Transcripts have no author, so "by user" means session participant.
        .apply_if(req.effective_relationship_ids(true), |q, ids| {
            q.filter(coaching_sessions::Column::CoachingRelationshipId.is_in(ids.iter().copied()))
        })
        .apply_if(f.coaching_session_id, |q, id| {
            q.filter(transcription::Column::CoachingSessionId.eq(id))
        });
    // A segment is never edited, so it was last updated when it was created.
    let mut matches = [f.created, f.updated]
        .into_iter()
        .fold(matches, created_within)
        .into_query();
    matches
        // Max, not sum, which would favor long rambling sessions.
        .expr_window_as(Func::max(fts.score(&cq)), per_transcription(), SCORE)
        .expr_window_as(
            Expr::cust("row_number()"),
            best_first,
            RANK_IN_TRANSCRIPTION,
        );

    let mut grouped = Query::select();
    grouped
        .column(Asterisk)
        .from_subquery(matches, "matches")
        .and_where(Expr::col(RANK_IN_TRANSCRIPTION).lte(SEGMENTS_PER_TRANSCRIPTION));
    if let Some(cursor) = req.cursor {
        grouped.cond_where(cursor_condition(
            || Expr::col(SCORE),
            Expr::col("id"),
            HitType::Transcript,
            cursor,
        ));
    }
    grouped
        .order_by(SCORE, Order::Desc)
        .order_by("id", Order::Asc)
        .limit(req.fetch)
        .take()
}

/// Narrow to segments created inside a half-open window.
fn created_within(select: Select<Entity>, window: TimeRange) -> Select<Entity> {
    select
        .apply_if(window.from, |q, v| q.filter(Column::CreatedAt.gte(v)))
        .apply_if(window.to_exclusive, |q, v| {
            q.filter(Column::CreatedAt.lt(v))
        })
}
